/* Single source of truth for the whole site.

   Times are seconds. Cost, admissions and CS-program fields come from the U.S.
   Department of Education College Scorecard (api.data.gov), matched school by
   school against an explicit name map — no fuzzy matching, because fuzzy matching
   produced confident false positives (Georgia State -> Georgia Tech and six others).

   Cross country data is transcribed from 2025 championship result pages on TFRRS.
   `xc.slot` is where he would have finished inside that team's scoring seven,
   averaged over every race of theirs on file; `xc.v7` is his projection minus
   their 7th man, so negative means inside the seven. See methodology.html §3.

   Detail data — every meet each team travelled to, the named top sevens, and
   venue coordinates — lives in detail.js, loaded only by school.html.

   Candidate list: every NCAA D1/D2/D3 school inside each ring that sponsors men's
   cross country, plus three named NAIA programs. The rings are
   250 driving miles of Greenville SC, 20 driving miles of midtown Manhattan
   *plus all of Long Island*, and 20 driving miles of the Chicago Loop. Sponsorship
   was checked conference by conference from each conference's sponsored-sports
   table, so a school missing here is a school whose conference table did not list
   men's cross country. NAIA and NCCAA coverage is known to be incomplete — see
   methodology.html §6a. Mileages past the original board are estimates: straight-line
   distance × 1.18, or × 1.35 in the mountain states, rounded to the nearest 5. */

